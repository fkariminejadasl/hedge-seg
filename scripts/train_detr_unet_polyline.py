"""
DETR-style polyline detector. Descends from train_detr_dino_polyline_rel.py
(now superseded) with these changes:

MapTR-style head (was: DINO-style flat polyline queries + diffusion refinement):
- Hierarchical queries: separate instance embedding + point embedding, so both
  the query position and the query content are learned per (instance, point).
- Iterative reference-point refinement in the decoder: each layer refines the
  previous layer's points and rebuilds the query positional embedding from the
  current reference point (MapTR-style, but with global attention, not
  deformable attention).
- Diffusion refinement stage removed.
- Geometric losses (bbox L1/gIoU, length, direction, smoothness, cardinality)
  are optional and off by default; only class + ordered point L1 (+ aux) are
  used. When length/direction are enabled, the forward/reverse GT orientation
  is chosen by the same ordered-L1 criterion as the polyline loss.

UNet-ResNet18 image backbone (was: precomputed DINOv3 embeddings of LiDAR crops), 
similar code as train_detr_maptr_polyline.py with these changes:
- Backbone on high-resolution PDOK aerial images (25 cm/px, 1000 x 1000),
  initialized from the train_semseg_unet_resnet18.py semseg checkpoint,
  freezable (frozen keeps BatchNorm in eval so semseg statistics are preserved).
- Dataset loads images + polyline NPZs produced by
  scripts/data/convert_pdok_polylines_to_detr_polyline.py.
- Images are zero-padded 1000 -> pad_to (default 1024, divisible by 32);
  polylines are normalized by the padded extent so they stay aligned with
  the feature grid.
- Optional flip/rot90 augmentation of image + polylines together.
- mode="preview" renders exactly what the model sees (padded, normalized,
  augmented image tensor + GT polylines) for visual verification.

Dataset: Generated by scripts/data/{build_pdok_wms_dataset.py,convert_pdok_polylines_to_detr_polyline.py}.
"""

