def _rot90_polylines(polylines: np.ndarray, k: int, size: int) -> np.ndarray:
    """
    Apply np.rot90(image, k) coordinate mapping to xy polylines on a square
    image of `size` pixels: one CCW rotation maps (x, y) -> (y, size-1-x).
    """
    for _ in range(k % 4):
        x = polylines[..., 0].copy()
        y = polylines[..., 1].copy()
        polylines[..., 0] = y
        polylines[..., 1] = (size - 1) - x
    return polylines


class DetrPolylineImageDataset(Dataset):
    """
    images from image_dir (pos_*.png etc.), GT from polyline_dir NPZs produced
    by scripts/data/convert_pdok_polylines_to_detr_polyline.py:
      polylines: (Ni,K,2) xy pixel coords
      labels: (Ni,)
      image_size: (2,) (H,W)

    Returns:
      image: (3, pad_to, pad_to) float, ImageNet-normalized, zero-padded
             bottom-right from (H,W)
      target: polylines normalized by (pad_to - 1) in [0,1]
    """

    IMAGE_SUFFIXES = [".png", ".jpg", ".jpeg", ".tif", ".tiff"]

    def __init__(
        self,
        image_dir: Path,
        polyline_dir: Path,
        num_points: int = 20,
        pad_to: int = 1024,
        augment: bool = False,
    ):
        self.image_dir = Path(image_dir)
        self.files = sorted(Path(polyline_dir).glob("*.npz"))
        self.num_points = num_points
        self.pad_to = pad_to
        self.augment = augment

    def __len__(self):
        return len(self.files)

    def _image_path(self, stem: str) -> Path:
        for suffix in self.IMAGE_SUFFIXES:
            candidate = self.image_dir / f"{stem}{suffix}"
            if candidate.exists():
                return candidate
        raise FileNotFoundError(f"No image for {stem} in {self.image_dir}")

    def __getitem__(self, idx: int):
        npz_path = self.files[idx]
        d = np.load(npz_path)

        polylines = np.ascontiguousarray(d["polylines"]).astype(np.float32)
        labels = torch.from_numpy(np.ascontiguousarray(d["labels"])).long()
        H, W = d["image_size"].tolist()

        if polylines.shape[0] > 0 and polylines.shape[1] != self.num_points:
            raise ValueError(
                f"{npz_path.name}: expected K={self.num_points}, got {polylines.shape[1]}"
            )

        image = Image.open(self._image_path(npz_path.stem)).convert("RGB")
        if image.size != (W, H):
            raise ValueError(
                f"{npz_path.stem}: image size {image.size} != npz image_size {(W, H)}"
            )
        arr = np.asarray(image, dtype=np.float32) / 255.0  # (H,W,3)

        if self.augment:
            if H != W:
                raise ValueError("augment=True requires square images")
            if np.random.rand() < 0.5:
                arr = arr[:, ::-1]
                polylines[..., 0] = (W - 1) - polylines[..., 0]
            if np.random.rand() < 0.5:
                arr = arr[::-1]
                polylines[..., 1] = (H - 1) - polylines[..., 1]
            k = np.random.randint(0, 4)
            if k:
                arr = np.rot90(arr, k)
                polylines = _rot90_polylines(polylines, k, W)

        if H > self.pad_to or W > self.pad_to:
            raise ValueError(f"{npz_path.stem}: image {(H, W)} larger than pad_to")
        padded = np.zeros((self.pad_to, self.pad_to, 3), dtype=np.float32)
        padded[:H, :W] = arr

        x = torch.from_numpy(padded).permute(2, 0, 1).contiguous()
        x = (x - IMAGENET_MEAN) / IMAGENET_STD

        polylines = torch.from_numpy(np.ascontiguousarray(polylines)).float()
        if polylines.numel() > 0:
            polylines = (polylines / float(self.pad_to - 1)).clamp(0, 1)

        target = {
            "labels": labels,
            "polylines": polylines,
            "image_size": np.asarray([H, W], dtype=np.int32),
            "pad_size": self.pad_to,
            "stem": npz_path.stem,
        }
        return x, target


class DetrPolylineImageFileListDataset(DetrPolylineImageDataset):
    def __init__(
        self,
        split_file: Path,
        image_dir: Path,
        num_points: int = 20,
        pad_to: int = 1024,
        augment: bool = False,
    ):
        split_file = Path(split_file)
        self.image_dir = Path(image_dir)
        self.files = []
        with open(split_file) as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                path = Path(line)
                if not path.is_absolute():
                    path = split_file.parent / path
                self.files.append(path)

        self.num_points = num_points
        self.pad_to = pad_to
        self.augment = augment


def detr_polyline_collate_fn(batch):
    images, targets = zip(*batch)
    images = torch.stack(images, dim=0)  # (B,3,pad,pad)
    return images, list(targets)


@torch.no_grad()
def preview_dataset(dataset, out_dir: Path, n: int = 8, dpi: int = 150):
    """
    Render exactly what the model sees: the padded/normalized (and possibly
    augmented) image tensor with its GT polylines, denormalized for display.
    Point order shown as color gradient (dark = first point).
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    n = min(n, len(dataset))
    for i in range(n):
        x, target = dataset[i]
        image = (x * IMAGENET_STD + IMAGENET_MEAN).clamp(0, 1)
        image = image.permute(1, 2, 0).numpy()
        S = image.shape[0]

        polys = target["polylines"]
        fig, ax = plt.subplots(figsize=(S / dpi, S / dpi), dpi=dpi)
        ax.imshow(image)
        cmap = plt.get_cmap("tab10")
        for j, poly in enumerate(polys):
            p = poly.numpy() * (S - 1)
            color = cmap(j % 10)
            ax.plot(p[:, 0], p[:, 1], "-", color=color, linewidth=1.0)
            order = np.linspace(0.3, 1.0, p.shape[0])
            ax.scatter(p[:, 0], p[:, 1], c=order, cmap="viridis", s=4, zorder=3)
            ax.plot(p[0, 0], p[0, 1], "o", color=color, markersize=5, zorder=4)
        ax.set_xlim(0, S - 1)
        ax.set_ylim(S - 1, 0)
        ax.axis("off")
        fig.tight_layout(pad=0)
        fig.savefig(out_dir / f"{target['stem']}_{i:02d}.png", bbox_inches="tight")
        plt.close(fig)
    print(f"Wrote {n} preview images to {out_dir}")


