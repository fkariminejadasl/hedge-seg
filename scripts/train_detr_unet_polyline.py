class DetrPolylineFromEmbeddings(nn.Module):
    """
    Input: x (B, L, in_dim), with L = grid_h * grid_w
    Output:
      pred_logits: (B, P, num_classes+1)
      pred_boxes: (B, P, 4) in [0,1], cxcywh
      pred_polylines: (B, P, K, 2) in [0,1]
      aux_outputs: list[dict], optional

    MapTR-style query layout:
      instance_embedding: (P, 2D)
      pts_embedding: (K, 2D)
      object_query_embed: (P*K, 2D), split into query_pos/query_content
      decoder hs: (num_layers, B, P*K, D) -> (num_layers, B, P, K, D)
    """

    def __init__(
        self,
        in_dim: int = 1024,
        num_classes: int = 1,
        num_polylines: int = 100,
        d_model: int = 256,
        nhead: int = 8,
        num_encoder_layers: int = 4,
        num_decoder_layers: int = 4,
        dim_feedforward: int = 1024,
        dropout: float = 0.1,
        grid_size: Tuple[int, int] = (16, 16),
        num_points: int = 20,
        aux_loss: bool = True,
        normalize_before: bool = False,
        query_embed_mode: str = "detr",  # "detr" or "legacy"
        with_refine: bool = True,
    ):
        super().__init__()
        assert query_embed_mode in {"detr", "legacy"}
        if with_refine and query_embed_mode != "detr":
            raise ValueError("with_refine=True requires query_embed_mode='detr'")

        self.num_classes = num_classes
        self.num_polylines = num_polylines
        self.num_queries = num_polylines * num_points
        self.grid_h, self.grid_w = grid_size
        self.num_points = num_points
        self.aux_loss = aux_loss
        self.query_embed_mode = query_embed_mode
        self.with_refine = with_refine

        self.input_proj = nn.Linear(in_dim, d_model)
        self.pos_embed = PositionEmbeddingSine2D(num_pos_feats=d_model // 2)
        self.instance_embedding = nn.Embedding(num_polylines, d_model * 2)
        self.pts_embedding = nn.Embedding(num_points, d_model * 2)

        if query_embed_mode == "detr":
            self.transformer = DETRTransformer(
                d_model=d_model,
                nhead=nhead,
                num_encoder_layers=num_encoder_layers,
                num_decoder_layers=num_decoder_layers,
                dim_feedforward=dim_feedforward,
                dropout=dropout,
                normalize_before=normalize_before,
                return_intermediate_dec=aux_loss,
            )
        else:
            self.transformer = LegacyTransformerWrapper(
                d_model=d_model,
                nhead=nhead,
                num_encoder_layers=num_encoder_layers,
                num_decoder_layers=num_decoder_layers,
                dim_feedforward=dim_feedforward,
                dropout=dropout,
                return_intermediate_dec=aux_loss,
            )

        self.class_embed = nn.Linear(d_model, num_classes + 1)
        self.reference_points = nn.Linear(d_model, 2)

        if with_refine:
            # Maps sine embedding of current reference point -> query_pos, per layer.
            self.ref_point_head = MLP(d_model, d_model, d_model, num_layers=2)
            # One offset head per decoder layer (MapTR-style iterative refinement).
            self.reg_branches = _get_clones(
                MLP(d_model, d_model, 2, num_layers=3), num_decoder_layers
            )
            # Zero-init so refinement starts as identity: layer outputs equal the
            # initial reference points, and offsets grow from zero.
            for reg in self.reg_branches:
                nn.init.zeros_(reg.layers[-1].weight)
                nn.init.zeros_(reg.layers[-1].bias)
        else:
            self.point_embed = MLP(d_model, d_model, 2, num_layers=3)

    def _build_hierarchical_queries(self) -> Tuple[torch.Tensor, torch.Tensor]:
        pts_embeds = self.pts_embedding.weight.unsqueeze(0)  # (1,K,2D)
        instance_embeds = self.instance_embedding.weight.unsqueeze(1)  # (P,1,2D)
        object_query_embed = (pts_embeds + instance_embeds).flatten(0, 1)  # (P*K,2D)
        query_pos, query_content = object_query_embed.chunk(2, dim=-1)  # (P*K,D)
        return query_pos, query_content

    def _decode_polylines(
        self,
        hs: torch.Tensor,  # (num_layers,B,P*K,D)
        query_pos: torch.Tensor,  # (P*K,D)
    ) -> torch.Tensor:
        reference_points = self.reference_points(query_pos).sigmoid()  # (P*K,2)
        point_logits = self.point_embed(hs)  # (num_layers,B,P*K,2)
        point_logits = point_logits + inverse_sigmoid(reference_points)[None, None]
        points = point_logits.sigmoid()

        return points.view(
            hs.shape[0],
            hs.shape[1],
            self.num_polylines,
            self.num_points,
            2,
        )

    @torch.jit.unused
    def _set_aux_loss(self, outputs_class, outputs_boxes, outputs_poly):
        return [
            {
                "pred_logits": a,
                "pred_boxes": b,
                "pred_polylines": c,
            }
            for a, b, c in zip(
                outputs_class[:-1], outputs_boxes[:-1], outputs_poly[:-1]
            )
        ]

    def forward(
        self, x: torch.Tensor, return_features: bool = False
    ) -> Dict[str, torch.Tensor]:
        B, L, _ = x.shape
        assert (
            L == self.grid_h * self.grid_w
        ), f"Expected {self.grid_h * self.grid_w} tokens, got {L}"

        dino_tokens = x
        src = self.input_proj(x)
        pos = self.pos_embed(B=B, H=self.grid_h, W=self.grid_w, device=x.device)
        query_pos, query_content = self._build_hierarchical_queries()

        reference_points = None
        if self.with_refine:
            reference_points = self.reference_points(query_pos).sigmoid()  # (P*K,2)
            reference_points = reference_points.unsqueeze(0).expand(B, -1, -1)

        mask = None
        hs, refs, memory = self.transformer(
            src=src,
            query_embed=query_pos,
            query_content=query_content,
            pos_embed=pos,
            mask=mask,
            reference_points=reference_points,
            reg_branches=self.reg_branches if self.with_refine else None,
            ref_point_head=self.ref_point_head if self.with_refine else None,
        )  # hs: (num_layers,B,P*K,D); refs: (num_layers,B,P*K,2) or None

        hs_poly = hs.view(
            hs.shape[0],
            B,
            self.num_polylines,
            self.num_points,
            hs.shape[-1],
        )  # (num_layers,B,P,K,D)
        outputs_class = self.class_embed(hs_poly.mean(dim=3))  # (num_layers,B,P,C+1)
        if self.with_refine:
            outputs_poly = refs.view(
                refs.shape[0], B, self.num_polylines, self.num_points, 2
            )  # (num_layers,B,P,K,2)
        else:
            outputs_poly = self._decode_polylines(hs, query_pos)
        outputs_boxes = box_xyxy_to_cxcywh(
            polyline_to_bbox_xyxy(outputs_poly)
        )  # (num_layers,B,P,4)

        out = {
            "pred_logits": outputs_class[-1],
            "pred_boxes": outputs_boxes[-1],
            "pred_polylines": outputs_poly[-1],
        }

        if return_features:
            out["memory"] = memory
            out["hs_last"] = hs_poly[-1].mean(dim=2)
            out["dino_tokens"] = dino_tokens

        if self.aux_loss:
            out["aux_outputs"] = self._set_aux_loss(
                outputs_class, outputs_boxes, outputs_poly
            )

        return out


class DetrPolylineFromImage(nn.Module):
    """
    Backbone (image -> feature map) + DetrPolylineFromEmbeddings (tokens -> polylines).

    Images must be (B, 3, pad_to, pad_to) with pad_to divisible by the backbone
    stride; the token grid is then (pad_to/stride, pad_to/stride).
    """

    def __init__(self, backbone: ResNet18UNetFeatures, detr: DetrPolylineFromEmbeddings):
        super().__init__()
        self.backbone = backbone
        self.detr = detr

    def forward(
        self, images: torch.Tensor, return_features: bool = False
    ) -> Dict[str, torch.Tensor]:
        feat = self.backbone(images)  # (B,C,h,w)
        B, C, h, w = feat.shape
        assert (h, w) == (self.detr.grid_h, self.detr.grid_w), (
            f"Feature grid {(h, w)} != detr grid {(self.detr.grid_h, self.detr.grid_w)}"
        )
        tokens = feat.flatten(2).transpose(1, 2)  # (B,h*w,C)
        return self.detr(tokens, return_features=return_features)


