class ConvBlock(nn.Module):
    def __init__(self, in_channels: int, out_channels: int):
        super().__init__()

        self.block = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_channels, out_channels, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
        )

    def forward(self, x):
        return self.block(x)


class UpBlock(nn.Module):
    def __init__(self, in_channels: int, skip_channels: int, out_channels: int):
        super().__init__()

        self.conv = ConvBlock(in_channels + skip_channels, out_channels)

    def forward(self, x, skip):
        x = F.interpolate(x, size=skip.shape[-2:], mode="bilinear", align_corners=False)
        x = torch.cat([x, skip], dim=1)
        x = self.conv(x)
        return x


class ResNet18UNet(nn.Module):
    def __init__(
        self,
        out_channels: int = 2,
        pretrained: bool = False,
    ):
        super().__init__()

        if pretrained:
            weights = torchvision.models.ResNet18_Weights.DEFAULT
        else:
            weights = None

        resnet = torchvision.models.resnet18(weights=weights)

        self.stem = nn.Sequential(
            resnet.conv1,
            resnet.bn1,
            resnet.relu,
        )
        self.maxpool = resnet.maxpool

        self.enc1 = resnet.layer1  # 64 channels, stride 4 after maxpool
        self.enc2 = resnet.layer2  # 128 channels, stride 8
        self.enc3 = resnet.layer3  # 256 channels, stride 16
        self.enc4 = resnet.layer4  # 512 channels, stride 32

        self.up3 = UpBlock(in_channels=512, skip_channels=256, out_channels=256)
        self.up2 = UpBlock(in_channels=256, skip_channels=128, out_channels=128)
        self.up1 = UpBlock(in_channels=128, skip_channels=64, out_channels=64)
        self.up0 = UpBlock(in_channels=64, skip_channels=64, out_channels=64)

        self.head = nn.Conv2d(64, out_channels, kernel_size=1)


FEATURE_STAGES = {
    "enc4": {"stride": 32, "channels": 512},
    "up3": {"stride": 16, "channels": 256},
}


class ResNet18UNetFeatures(nn.Module):
    """
    Feature extractor on top of the semseg-trained ResNet18UNet.

    feature_stage:
      "enc4": stride 32, 512 channels (cheapest)
      "up3":  stride 16, 256 channels (higher resolution for thin polylines)

    When frozen, parameters get no gradient and BatchNorm stays in eval mode
    so running statistics are not updated by the polyline training data.
    """

    def __init__(
        self,
        ckpt_path: Optional[Path] = None,
        feature_stage: str = "up3",
        frozen: bool = True,
    ):
        super().__init__()
        assert feature_stage in FEATURE_STAGES
        self.feature_stage = feature_stage
        self.frozen = frozen
        self.stride = FEATURE_STAGES[feature_stage]["stride"]
        self.out_channels = FEATURE_STAGES[feature_stage]["channels"]

        self.unet = ResNet18UNet(out_channels=2, pretrained=False)
        if ckpt_path is not None:
            # weights_only=False: the semseg checkpoint stores its cfg (with
            # PosixPath objects) next to the state dict.
            ckpt = torch.load(ckpt_path, map_location="cpu", weights_only=False)
            state = ckpt["model"] if "model" in ckpt else ckpt
            self.unet.load_state_dict(state, strict=True)
            print(f"Loaded backbone checkpoint from {ckpt_path}")

        if frozen:
            for p in self.unet.parameters():
                p.requires_grad_(False)

    def train(self, mode: bool = True):
        super().train(mode)
        if self.frozen:
            self.unet.eval()
        return self

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        ctx = torch.no_grad() if self.frozen else nullcontext()
        with ctx:
            s0 = self.unet.stem(x)
            x = self.unet.maxpool(s0)
            s1 = self.unet.enc1(x)
            s2 = self.unet.enc2(s1)
            s3 = self.unet.enc3(s2)
            x4 = self.unet.enc4(s3)

            if self.feature_stage == "enc4":
                return x4  # (B,512,H/32,W/32)
            return self.unet.up3(x4, s3)  # (B,256,H/16,W/16)


