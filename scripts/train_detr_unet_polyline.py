        train_losses = train_one_epoch(
            train_loader, model, criterion, optimizer, device
        )
        run_eval = (epoch % cfg.eval_every == 0) or (epoch == cfg.n_epochs)
        eval_losses = (
            eval_one_epoch(eval_loader, model, criterion, device)
            if run_eval
            else None
        )

