def main(cfg):
    set_seed(cfg.seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    if device.type == "cuda":
        print(f"Using device: {torch.cuda.get_device_properties()}")

    stage = FEATURE_STAGES[cfg.feature_stage]
    assert cfg.pad_to % stage["stride"] == 0
    grid = cfg.pad_to // stage["stride"]

    backbone = ResNet18UNetFeatures(
        ckpt_path=cfg.backbone_ckpt,
        feature_stage=cfg.feature_stage,
        frozen=cfg.freeze_backbone,
    )
    detr = DetrPolylineFromEmbeddings(
        in_dim=stage["channels"],
        num_classes=cfg.num_classes,
        num_polylines=cfg.num_polylines,
        d_model=cfg.d_model,
        nhead=cfg.nhead,
        num_encoder_layers=cfg.num_encoder_layers,
        num_decoder_layers=cfg.num_decoder_layers,
        dim_feedforward=cfg.dim_feedforward,
        dropout=cfg.dropout,
        grid_size=(grid, grid),
        num_points=cfg.num_points,
        aux_loss=cfg.aux_loss,
        query_embed_mode=cfg.query_embed_mode,
        with_refine=cfg.with_refine,
    )
    model = DetrPolylineFromImage(backbone, detr).to(device)
    n_trainable = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(
        f"Feature stage: {cfg.feature_stage} (stride {stage['stride']}, "
        f"grid {grid}x{grid}), trainable params: {n_trainable / 1e6:.1f}M"
    )

    if cfg.mode == "preview":
        preview_ds = DetrPolylineImageDataset(
            image_dir=cfg.image_dir,
            polyline_dir=cfg.polyline_dir,
            num_points=cfg.num_points,
            pad_to=cfg.pad_to,
            augment=cfg.augment,
        )
        preview_dataset(preview_ds, Path(cfg.preview_out_dir), n=cfg.preview_n)
        return

    if cfg.mode == "infer":
        if cfg.infer_ckpt is None:
            raise ValueError("For mode='infer', cfg.infer_ckpt must be set.")
        load_checkpoint_flexible(model, cfg.infer_ckpt, key_candidates=["model"])

        if cfg.infer_split_file is not None:
            infer_ds = DetrPolylineImageFileListDataset(
                split_file=cfg.infer_split_file,
                image_dir=cfg.image_dir,
                num_points=cfg.num_points,
                pad_to=cfg.pad_to,
                augment=False,
            )
        elif cfg.infer_polyline_dir is not None:
            infer_ds = DetrPolylineImageDataset(
                image_dir=cfg.image_dir,
                polyline_dir=cfg.infer_polyline_dir,
                num_points=cfg.num_points,
                pad_to=cfg.pad_to,
                augment=False,
            )
        else:
            raise ValueError(
                "For mode='infer', set cfg.infer_split_file or cfg.infer_polyline_dir."
            )

        infer_loader = DataLoader(
            infer_ds,
            batch_size=cfg.batch_size,
            shuffle=False,
            num_workers=cfg.num_workers,
            collate_fn=detr_polyline_collate_fn,
            persistent_workers=cfg.num_workers > 0,
        )
        infer_model(infer_loader, model, device, cfg)
        return

    if cfg.mode != "train":
        raise ValueError("cfg.mode must be 'train', 'infer' or 'preview'.")

    # Two dataset views over the same files: augmentation only on train.
    dataset = DetrPolylineImageDataset(
        image_dir=cfg.image_dir,
        polyline_dir=cfg.polyline_dir,
        num_points=cfg.num_points,
        pad_to=cfg.pad_to,
        augment=cfg.augment,
    )
